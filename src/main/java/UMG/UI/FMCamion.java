    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        try {
            String matricula = txtMatricula.getText().trim();

            if (matricula.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Ingrese la matrícula del camión.");
                return;
            }

            CamionDAO dao = new CamionDAO();
            Camion camion = dao.buscar(matricula);

            if (camion != null) {
                txtModelo.setText(camion.getModelo());
                txtTipo.setText(camion.getTipo());
                txtPotencia.setText(
                        String.valueOf(camion.getPotencia()));

                JOptionPane.showMessageDialog(this,
                        "Camión encontrado correctamente.");
            } else {
                JOptionPane.showMessageDialog(this,
                        "No se encontró un camión con esa matrícula.");
            }

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                    "Error al consultar: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            String matricula = txtMatricula.getText().trim();
            String modelo = txtModelo.getText().trim();
            String tipo = txtTipo.getText().trim();
            String textoPotencia = txtPotencia.getText().trim();

            if (matricula.isEmpty() || modelo.isEmpty()
                    || tipo.isEmpty() || textoPotencia.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Completa todos los campos.");
                return;
            }

            int potencia = Integer.parseInt(textoPotencia);

            if (potencia <= 0) {
                JOptionPane.showMessageDialog(this,
                        "La potencia debe ser mayor que cero.");
                return;
            }

            Camion camion = new Camion(matricula, modelo, tipo, potencia);
            CamionDAO dao = new CamionDAO();

            if (dao.insertar(camion)) {
                JOptionPane.showMessageDialog(this,
                        "Camión guardado correctamente.");
                txtMatricula.setText("");
                txtModelo.setText("");
                txtTipo.setText("");
                txtPotencia.setText("");
            }

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "La potencia debe ser un número entero.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                    "Error al guardar: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

