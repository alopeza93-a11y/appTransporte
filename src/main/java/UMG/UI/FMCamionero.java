    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
try {
    if (txtDni.getText().trim().isEmpty()
            || txtNombre.getText().trim().isEmpty()
            || txtTelefono.getText().trim().isEmpty()
            || txtDireccion.getText().trim().isEmpty()
            || txtSalario.getText().trim().isEmpty()
            || txtPoblacion.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Todos los campos son obligatorios.");
        return;
    }

    double salario = Double.parseDouble(txtSalario.getText().trim());

    if (salario < 0) {
        JOptionPane.showMessageDialog(this,
                "El salario no puede ser negativo.");
        return;
    }

    Camionero camionero = new Camionero(
            txtDni.getText().trim(),
            txtNombre.getText().trim(),
            txtTelefono.getText().trim(),
            txtDireccion.getText().trim(),
            salario,
            txtPoblacion.getText().trim()
    );

    CamioneroDAO dao = new CamioneroDAO();

    if (dao.insertar(camionero)) {
        JOptionPane.showMessageDialog(this,
                "Camionero guardado correctamente.");
    }

} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this,
            "El salario debe ser un número válido.");
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this,
            "Error al guardar: " + ex.getMessage());
}

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       
try {
    String dni = txtDni.getText().trim();

    if (dni.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Ingresa el DNI del camionero.");
        return;
    }

    CamioneroDAO dao = new CamioneroDAO();
    Camionero camionero = dao.buscar(dni);

    if (camionero != null) {
        txtNombre.setText(camionero.getNombre());
        txtTelefono.setText(camionero.getTelefono());
        txtDireccion.setText(camionero.getDireccion());
        txtSalario.setText(String.valueOf(camionero.getSalario()));
        txtPoblacion.setText(camionero.getPoblacion());

        JOptionPane.showMessageDialog(this,
                "Camionero encontrado correctamente.");
    } else {
        JOptionPane.showMessageDialog(this,
                "No se encontró un camionero con ese DNI.");
    }

} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this,
            "Error al consultar: " + ex.getMessage());
}

    }//GEN-LAST:event_jButton2ActionPerformed

