    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        
try {
    String dni = txtDni.getText().trim();

    if (dni.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Ingresa el DNI del camionero que deseas eliminar.");
        return;
    }

    int confirmacion = JOptionPane.showConfirmDialog(this,
            "¿Estás seguro de eliminar al camionero con DNI " + dni + "?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION);

    if (confirmacion != JOptionPane.YES_OPTION) {
        return;
    }

    CamioneroDAO dao = new CamioneroDAO();

    if (dao.eliminar(dni)) {
        JOptionPane.showMessageDialog(this,
                "Camionero eliminado correctamente.");

        txtDni.setText("");
        txtNombre.setText("");
        txtTelefono.setText("");
        txtDireccion.setText("");
        txtSalario.setText("");
        txtPoblacion.setText("");
        txtDni.requestFocusInWindow();
    } else {
        JOptionPane.showMessageDialog(this,
                "No se encontró un camionero con ese DNI.");
    }

} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this,
            "Error al eliminar: " + ex.getMessage());
}

    }//GEN-LAST:event_jButton4ActionPerformed

