    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

String dni = txtDniCamionero.getText().trim();
String matricula = txtMatricula.getText().trim();
String fechaTexto = txtFecha.getText().trim();

if (dni.isEmpty() || matricula.isEmpty() || fechaTexto.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Ingresa el DNI, la matrícula y la fecha de la asignación.");
    return;
}

try {
    java.sql.Date fecha = java.sql.Date.valueOf(fechaTexto);

    int confirmar = JOptionPane.showConfirmDialog(
            this,
            "¿Deseas eliminar esta asignación?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION
    );

    if (confirmar != JOptionPane.YES_OPTION) {
        return;
    }

    CamioneroCamionDAO dao = new CamioneroCamionDAO();
    boolean eliminado = dao.eliminar(dni, matricula, fecha);

    if (eliminado) {
        JOptionPane.showMessageDialog(this,
                "Asignación eliminada correctamente.");
        txtDniCamionero.setText("");
        txtMatricula.setText("");
        txtFecha.setText("");
    } else {
        JOptionPane.showMessageDialog(this,
                "No se encontró una asignación con esos datos.");
    }

} catch (IllegalArgumentException ex) {
    JOptionPane.showMessageDialog(this,
            "La fecha debe tener el formato AAAA-MM-DD.");
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this,
            "Error al eliminar: " + ex.getMessage());
}

    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        
String dni = txtDniCamionero.getText().trim();
String matricula = txtMatricula.getText().trim();
String fechaTexto = txtFecha.getText().trim();

if (dni.isEmpty() || matricula.isEmpty() || fechaTexto.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Completa todos los campos.");
    return;
}

try {
    Date fecha = Date.valueOf(LocalDate.parse(fechaTexto));

    CamioneroCamion asignacion =
            new CamioneroCamion(dni, matricula, fecha);

    CamioneroCamionDAO dao = new CamioneroCamionDAO();

    if (dao.insertar(asignacion)) {
        JOptionPane.showMessageDialog(this,
                "Asignación guardada correctamente.");
    }

} catch (DateTimeParseException | IllegalArgumentException ex) {
    JOptionPane.showMessageDialog(this,
            "Verifica la fecha. Usa el formato AAAA-MM-DD.");
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this,
            "Error al guardar la asignación:\n" + ex.getMessage());
}

    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
try {
    CamioneroCamionDAO dao = new CamioneroCamionDAO();
    java.util.List<CamioneroCamion> lista = dao.listar();

    if (lista.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "No hay asignaciones registradas.");
        return;
    }

    StringBuilder mensaje = new StringBuilder();

    for (CamioneroCamion a : lista) {
        mensaje.append("DNI: ")
                .append(a.getDniCamionero())
                .append("\nMatrícula: ")
                .append(a.getMatricula())
                .append("\nFecha: ")
                .append(a.getFecha())
                .append("\n----------------------\n");
    }

    JOptionPane.showMessageDialog(this,
            mensaje.toString(),
            "Asignaciones registradas",
            JOptionPane.INFORMATION_MESSAGE);

} catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Error al consultar: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnConsultarActionPerformed

